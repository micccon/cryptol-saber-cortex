#include <stdio.h>
#include <string.h>

#include "kem.h"
#include "randombytes.h"
#include "../third_party/fips202.h"

static const uint8_t kat_seed[48] = {
    0x06, 0x15, 0x50, 0x23, 0x4d, 0x15, 0x8c, 0x5e,
    0xc9, 0x55, 0x95, 0xfe, 0x04, 0xef, 0x7a, 0x25,
    0x76, 0x7f, 0x2e, 0x24, 0xcc, 0x2b, 0xc4, 0x79,
    0xd0, 0x9d, 0x86, 0xdc, 0x9a, 0xbc, 0xfd, 0xe7,
    0x05, 0x6a, 0x8c, 0x26, 0x6f, 0x9e, 0xf9, 0x7e,
    0xd0, 0x85, 0x41, 0xdb, 0xd2, 0xe1, 0xff, 0xa1
};

static int check_round_trip(void) {
    pk_t pk;
    kem_sk_t sk;
    ct_t ct;
    uint8_t ss_enc[SABER_KEYBYTES];
    uint8_t ss_dec[SABER_KEYBYTES];
    uint8_t digest[32];
    static const uint8_t expected_seed_a[SABER_SEEDBYTES] = {
        0xe9, 0xf2, 0xac, 0x32, 0x93, 0x54, 0x89, 0xc7,
        0xed, 0xd0, 0x64, 0xbb, 0xa9, 0xa7, 0x8c, 0xea,
        0xb0, 0x9d, 0x29, 0xe0, 0x20, 0xc0, 0xea, 0x8f,
        0x1c, 0x70, 0xd3, 0x3a, 0x81, 0x38, 0x89, 0xc3
    };
    static const uint8_t expected_z[SABER_KEYBYTES] = {
        0x14, 0x7c, 0x03, 0xf7, 0xa5, 0xbe, 0xbb, 0xa4,
        0x06, 0xc8, 0xfa, 0xe1, 0x87, 0x4d, 0x7f, 0x13,
        0xc8, 0x0e, 0xfe, 0x79, 0xa3, 0xa9, 0xa8, 0x74,
        0xcc, 0x09, 0xfe, 0x76, 0xf6, 0x99, 0x76, 0x15
    };
    static const uint8_t expected_hash_pk[32] = {
        0x3b, 0x36, 0x12, 0x37, 0xc9, 0xa1, 0xdf, 0xdf,
        0x5c, 0xc4, 0x84, 0x71, 0xc3, 0x67, 0xf4, 0xdc,
        0x84, 0xa3, 0xbe, 0xdc, 0x80, 0xb2, 0xd4, 0xb6,
        0x05, 0xc6, 0xfe, 0x8b, 0xed, 0x14, 0x1d, 0x29
    };
    static const uint8_t expected_pk_hash[32] = {
        0xc4, 0xa8, 0x05, 0xb3, 0x87, 0x0d, 0x9b, 0xec,
        0xe2, 0xb7, 0xd9, 0x7b, 0xfa, 0x03, 0x20, 0xa9,
        0x61, 0x65, 0x52, 0x19, 0x43, 0x12, 0x7d, 0x5c,
        0x94, 0x59, 0xbb, 0x74, 0x46, 0x77, 0x41, 0x58
    };
    static const uint8_t expected_indcpa_sk_hash[32] = {
        0xd5, 0x37, 0x0e, 0xb5, 0x50, 0xd9, 0x23, 0x04,
        0xf6, 0x69, 0xa9, 0xe8, 0x2e, 0xbe, 0x74, 0x13,
        0x29, 0x7a, 0xcf, 0x12, 0x66, 0x8a, 0xd3, 0xf8,
        0x76, 0x76, 0x31, 0x38, 0x0a, 0xe4, 0x56, 0xed
    };
    static const uint8_t expected_ct_hash[32] = {
        0x80, 0x61, 0x16, 0x83, 0x60, 0x4a, 0x36, 0x56,
        0x60, 0x42, 0x50, 0xfc, 0xb3, 0x9d, 0xf7, 0x7f,
        0x1d, 0xc0, 0x45, 0x3d, 0x5b, 0x66, 0x5c, 0xd0,
        0xa9, 0x23, 0x6e, 0x07, 0x06, 0xeb, 0xe0, 0x20
    };
    static const uint8_t expected_ss[SABER_KEYBYTES] = {
        0xa3, 0x55, 0x67, 0xb9, 0x62, 0xb8, 0xe1, 0x85,
        0x6d, 0xc6, 0x78, 0x7e, 0xca, 0x0d, 0xe4, 0x9c,
        0x4e, 0x8d, 0x4f, 0xcb, 0x87, 0x8f, 0x22, 0xdb,
        0xe7, 0x41, 0x48, 0xe0, 0x18, 0x91, 0xf2, 0xad
    };

    randombytes_init((uint8_t *)kat_seed, NULL, 256);
    KEM_KeyGen(&pk, &sk);
    KEM_Encaps(&pk, ss_enc, &ct);
    KEM_Decaps(&ct, &sk, ss_dec);

    if (memcmp(pk.seed_a, expected_seed_a, SABER_SEEDBYTES) != 0) {
        puts("KEM seed_a mismatch");
        return 1;
    }

    if (memcmp(sk.z, expected_z, SABER_KEYBYTES) != 0) {
        puts("KEM z mismatch");
        return 1;
    }

    if (memcmp(sk.hash_pk, expected_hash_pk, sizeof(sk.hash_pk)) != 0) {
        puts("KEM hash_pk mismatch");
        return 1;
    }

    sha3_256(digest, pk.pk, sizeof(pk.pk));
    if (memcmp(digest, expected_pk_hash, sizeof(digest)) != 0) {
        puts("KEM pk hash mismatch");
        return 1;
    }

    sha3_256(digest, sk.indcpa_sk.sk, sizeof(sk.indcpa_sk.sk));
    if (memcmp(digest, expected_indcpa_sk_hash, sizeof(digest)) != 0) {
        puts("KEM indcpa sk hash mismatch");
        return 1;
    }

    sha3_256(digest, ct.bytes, sizeof(ct.bytes));
    if (memcmp(digest, expected_ct_hash, sizeof(digest)) != 0) {
        puts("KEM ct hash mismatch");
        return 1;
    }

    if (memcmp(ss_enc, expected_ss, SABER_KEYBYTES) != 0) {
        puts("KEM shared secret mismatch");
        return 1;
    }

    if (memcmp(ss_enc, ss_dec, SABER_KEYBYTES) != 0) {
        puts("KEM round-trip failed");
        return 1;
    }

    return 0;
}

int main(void) {
    if (check_round_trip() != 0) {
        return 1;
    }

    puts("KEM smoke test passed");
    return 0;
}
